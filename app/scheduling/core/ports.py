"""Integration seams; fake identity/session implementations belong to demo_app only."""
from typing import Protocol
from .schemas import Actor, Horizon, Interval, ProviderSnapshot, Reservation


class ActorProvider(Protocol):
    def __call__(self) -> Actor: ...


class CalendarProvider(Protocol):
    def read_snapshot(self, owner_id: str, horizon: Horizon) -> ProviderSnapshot: ...


class SessionGateway(Protocol):
    def confirmed_reservations(self, subject_id: str, horizon: Interval) -> list[Reservation]: ...


class ScheduleRepository(Protocol):
    def read_bundle(self, owner_id: str) -> dict: ...
    def private_events(self, owner_id: str) -> list: ...
    def list_records(self, owner_id: str, kind: str) -> list: ...
    def create_record(self, owner_id: str, kind: str, data, record_id: str | None = None): ...
    def patch_record(self, owner_id: str, kind: str, record_id: str, changes: dict): ...
    def delete_record(self, owner_id: str, kind: str, record_id: str) -> bool: ...
    def begin_refresh(self, owner_id: str) -> int: ...
    def finish_refresh(self, owner_id: str, ticket: int, snapshot, now) -> bool: ...
    def fail_refresh(self, owner_id: str, ticket: int) -> None: ...
